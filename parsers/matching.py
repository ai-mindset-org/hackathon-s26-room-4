WEIGHTS = {"view": 0.35, "cut": 0.30, "state": 0.20, "title": 0.15}
AUTO, REVIEW = 0.85, 0.60


# Слова описаний, которые не про товар и только мешают сравнению названий.
NOISE = ("продукция", "доп информация", "информация", "вес упаковки",
         "размерный ряд", "качество", "поставка", "напрямую", "производства",
         "хранение", "месяцев", "в наличии", "цена", "руб")


def _find(text: str, table: dict[str, tuple[str, ...]]) -> str:
    low = " " + _fold(text) + " "
    for key, variants in table.items():
        if any(v in low for v in variants):
            return key
    return ""


def _clean_title(title: str) -> str:
    """Название без служебных слов источника — иначе «Доп. информация» и «Вес
    упаковки» дают ложное сходство двум совершенно разным товарам."""
    low = _fold(title)
    for word in NOISE:
        low = low.replace(word, " ")
    return re.sub(r"\s+", " ", re.sub(r"[^\wа-я ]", " ", low)).strip()


def features(title: str) -> dict:
    """Название → структурные признаки. Это и есть «паспорт» позиции."""
    weight = re.search(r"(\d+[.,]?\d*)\s?(кг|г|гр|л)\b", _fold(title))
    return {
        "view": _find(title, VIEW),
        "cut": _find(title, CUT),
        "state": _find(title, STATE),
        "weight": weight.group(0) if weight else "",
        "title": _clean_title(title),
    }


def score(a: str, b: str) -> dict:
    """Насколько это один и тот же товар. Возвращает балл и разбор по признакам."""
    fa, fb = features(a), features(b)
    parts: dict[str, float] = {}

    # Вид животного — БЛОКИРУЮЩИЙ признак, а не весовой. Разведка по
    # классификаторам (docs/research-classifiers.md) показала: официальные
    # системы дают устойчивый код ровно на уровне «вид + термосостояние», и
    # именно этот уровень нельзя размывать весами. Пока вид участвовал в общем
    # балле, «Цыплята отборные» подтягивали «Яйца куриные» на 0.67 — оба
    # куриные по тексту, но это разные транки, и склеивать их нельзя ни при
    # какой уверенности.
    if fa["view"] and fb["view"] and fa["view"] != fb["view"]:
        return {"score": 0.0, "decision": "разные товары",
                "parts": {"view": 0.0, "cut": 0.0, "state": 0.0, "title": 0.0},
                "a": fa, "b": fb, "blocked_by": "вид"}

    for field in ("view", "cut", "state"):
        if not fa[field] and not fb[field]:
            parts[field] = 0.5          # обоим нечем похвастаться — нейтрально
        elif not fa[field] or not fb[field]:
            parts[field] = 0.35         # у одного признака нет — мягкий штраф
        else:
            parts[field] = 1.0 if fa[field] == fb[field] else 0.0

    parts["title"] = SequenceMatcher(None, fa["title"], fb["title"]).ratio()
    total = sum(parts[k] * WEIGHTS[k] for k in WEIGHTS)

    decision = ("совпало" if total >= AUTO else
                "на подтверждение" if total >= REVIEW else "разные товары")
    return {"score": round(total, 3), "decision": decision,
            "parts": {k: round(v, 2) for k, v in parts.items()},
            "a": fa, "b": fb}


def match(title: str, candidates: list[str]) -> list[dict]:
    """Кандидаты, отсортированные по убыванию совпадения."""
    scored = [dict(score(title, c), candidate=c) for c in candidates]
    return sorted(scored, key=lambda r: -r["score"])
