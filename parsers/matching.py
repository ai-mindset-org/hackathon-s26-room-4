from difflib import SequenceMatcher

# ── Словари структурных признаков ────────────────────────────────────────────
# Порядок внутри группы важен: длинные варианты проверяются первыми,
# иначе «филе грудки» схлопнется в «филе».

def _fold(text: str) -> str:
    """ё→е и хвосты слов долой. Половина промахов классификатора была именно
    здесь: в словаре «цыплён», в данных «цыпленка» — и «Филе грудки
    цыпленка-бройлера» не опознавалось вообще."""
    return re.sub(r"\s+", " ", str(text or "").lower().replace("ё", "е"))


