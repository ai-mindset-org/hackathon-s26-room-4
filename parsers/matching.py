"""Сопоставление одного товара у разных поставщиков.

Задача, об которую мы спотыкались весь день: «Говядина Рибай» у заказчика,
«Мясо Говядина (лопатка)» у Фуд Сити, «Тушка трески П/Б/Г 2L» у Уайк ООО.
Артикула у еды нет, названия у всех свои.

Метод взят не из головы — это канон отраслевых решений (`Zarenk/product-matcher`,
`athulya-anil/Product_Dedupe`, `worldbank/FuzzyAI`), переложенный на еду.
Главный урок оттуда: **текст склеивает варианты одного товара, спасают
структурные признаки.** У мебели это цвет и размер (веса 0.18 и 0.12), у еды —
отруб, обработка и калибр. Их вес должен быть выше веса названия, иначе
«Рибай» и «лопатка» склеятся: по тексту они похожи, по деньгам различаются вдвое.

Три исхода вместо двух — тоже оттуда:

    ≥ 0.85   склеиваем сами
    0.6-0.85 показываем закупщику: «похоже, но не уверены» — он решает один раз
    < 0.6    разные товары

Средняя полоса и есть главное отличие от наивного матчинга: инструмент не
обязан быть уверенным, он обязан не врать молча.
"""

from __future__ import annotations

import re
from difflib import SequenceMatcher

# ── Словари структурных признаков ────────────────────────────────────────────
# Порядок внутри группы важен: длинные варианты проверяются первыми,
# иначе «филе грудки» схлопнется в «филе».

VIEW = {  # что за животное или рыба
    "говядина": ("говядин", "телятин", "быки", "коровы", "тёлки", "телки",
                 "бычки", "волы", "крс", "рибай", "стейк"),
    "свинина": ("свинин", "свиньи", "поросён", "порося"),
    "баранина": ("баранин", "ягнят", "барашк"),
    "курица": ("курин", "куры", "цыплён", "цыплят", "бройлер", "кур "),
    "индейка": ("индейк", "индюш"),
    "утка": ("утка", "утин"),
    "треска": ("треск",),
    "лосось": ("лосос", "сёмга", "семга"),
    "форель": ("форел",),
    "минтай": ("минта",),
    "горбуша": ("горбуш",),
    "скумбрия": ("скумбри",),
    "креветка": ("кревет",),
}

CUT = {  # отруб или часть — САМЫЙ дорогой по деньгам признак
    "вырезка": ("вырезка", "вырезк"),
    "рибай": ("рибай", "ribeye"),
    "филе-грудки": ("филе грудки", "грудка", "грудк"),
    "филе": ("филе",),
    "окорочка": ("окорочк", "ножки", "голень", "бедро", "legs"),
    "лопатка": ("лопатк",),
    "шейка": ("шейк",),
    "тушка": ("тушка", "тушк", "псг", "п/б/г", "неразделан", "целиком"),
    "теша": ("теша",),
    "фарш": ("фарш",),
    "субпродукты": ("субпродукт", "рубец", "печен", "сердц"),
}

STATE = {  # обработка — второй по силе признак
    "охлаждённое": ("охлажд", "охл.", " охл", "псг"),
    "замороженное": ("заморож", "зам.", " с/м", "св/м", "мороже", "в/м", "iqf"),
    "солёное": ("солён", "солен", "малосол", "слабосол"),
    "копчёное": ("копчён", "копчен", " хк", " гк"),
    "варёное": ("варён", "варен"),
}

WEIGHTS = {"view": 0.35, "cut": 0.30, "state": 0.20, "title": 0.15}
AUTO, REVIEW = 0.85, 0.60


def _find(text: str, table: dict[str, tuple[str, ...]]) -> str:
    low = " " + re.sub(r"\s+", " ", str(text or "").lower()) + " "
    for key, variants in table.items():
        if any(v in low for v in variants):
            return key
    return ""


def features(title: str) -> dict:
    """Название → структурные признаки. Это и есть «паспорт» позиции."""
    weight = re.search(r"(\d+[.,]?\d*)\s?(кг|г|гр|л)\b", str(title or "").lower())
    return {
        "view": _find(title, VIEW),
        "cut": _find(title, CUT),
        "state": _find(title, STATE),
        "weight": weight.group(0) if weight else "",
        "title": re.sub(r"[^\wа-яё ]", " ", str(title or "").lower()).strip(),
    }


def score(a: str, b: str) -> dict:
    """Насколько это один и тот же товар. Возвращает балл и разбор по признакам."""
    fa, fb = features(a), features(b)
    parts: dict[str, float] = {}

    for field in ("view", "cut", "state"):
        if not fa[field] and not fb[field]:
            parts[field] = 0.5          # обоим нечем похвастаться — нейтрально
        elif not fa[field] or not fb[field]:
            parts[field] = 0.35         # у одного признака нет — мягкий штраф
        else:
            parts[field] = 1.0 if fa[field] == fb[field] else 0.0

    parts["title"] = SequenceMatcher(None, fa["title"], fb["title"]).ratio()
    total = sum(parts[k] * WEIGHTS[k] for k in WEIGHTS)

    decision = ("совпало" if total >= AUTO else
                "на подтверждение" if total >= REVIEW else "разные товары")
    return {"score": round(total, 3), "decision": decision,
            "parts": {k: round(v, 2) for k, v in parts.items()},
            "a": fa, "b": fb}


def match(title: str, candidates: list[str]) -> list[dict]:
    """Кандидаты, отсортированные по убыванию совпадения."""
    scored = [dict(score(title, c), candidate=c) for c in candidates]
    return sorted(scored, key=lambda r: -r["score"])
